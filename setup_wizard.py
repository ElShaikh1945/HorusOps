def main():
    import argparse
    parser = argparse.ArgumentParser(description="HorusOps Configuration Setup Wizard")
    parser.add_argument("--port", type=int, default=8585, help="Port to run web wizard on (default: 8585)")
    parser.add_argument("--cli", "-c", action="store_true", help="Run in interactive terminal CLI mode (for VPS/headless)")
    args = parser.parse_args()

    if args.cli:
        try:
            run_cli_wizard()
        except (KeyboardInterrupt, EOFError):
            print("\n\n[INFO] تم إنهاء معالج الإعداد التفاعلي.")
        return

    port = get_free_port(args.port)
    server_address = ("127.0.0.1", port)
    httpd = http.server.ThreadingHTTPServer(server_address, SetupRequestHandler)
    httpd.daemon_threads = True
    url = f"http://localhost:{port}"

    print("=" * 65)
    print(" [CONFIG] HorusOps | Configuration Setup Wizard")
    print("=" * 65)
    print(f"\n[INFO] Web Setup running at: {url}\n")
    print("Press Ctrl+C in this terminal to stop.")
    print("=" * 65)

    try:
        webbrowser.open(url)
    except Exception:
        pass

    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nShutting down setup wizard. Goodbye!")
        httpd.server_close()


if __name__ == "__main__":
    main()
