def select_folder_native() -> str:
    try:
        if sys.platform == "darwin":
            cmd = [
                "osascript",
                "-e",
                'try\nset f to POSIX path of (choose folder with prompt "اختر مجلد المشاريع:")\nreturn f\non error\nreturn ""\nend try',
            ]
            res = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
            return res.stdout.strip().rstrip("/")
        elif sys.platform.startswith("linux"):
            if subprocess.run(["which", "zenity"], capture_output=True).returncode == 0:
                res = subprocess.run(["zenity", "--file-selection", "--directory", "--title=اختر مجلد المشاريع"], capture_output=True, text=True, timeout=60)
                return res.stdout.strip().rstrip("/")
            elif subprocess.run(["which", "kdialog"], capture_output=True).returncode == 0:
                res = subprocess.run(["kdialog", "--getexistingdirectory"], capture_output=True, text=True, timeout=60)
                return res.stdout.strip().rstrip("/")
    except Exception:
        pass
    return ""


def get_repo_branch(repo_path: Path) -> str:
    head = repo_path / ".git" / "HEAD"
    if head.is_file():
        try:
            c = head.read_text().strip()
            if c.startswith("ref: refs/heads/"):
                return c.split("refs/heads/")[1]
        except Exception:
            pass
    return "main"


def scan_repositories_in_paths(paths: list[str]) -> list[dict]:
    repos = []
    seen = set()
    ignored = {"ignore", "personal", "archive", "node_modules", ".venv", "dist", "build", ".git"}
    for p_str in paths:
        if not p_str or not p_str.strip():
            continue
        p = Path(p_str.strip()).expanduser()
        if not p.is_dir():
            continue
        p_res = p.resolve()
        if (p_res / ".git").exists():
            r_str = str(p_res)
            if r_str not in seen:
                seen.add(r_str)
                repos.append({"name": p_res.name, "path": r_str, "branch": get_repo_branch(p_res)})
        try:
            for item in sorted(p_res.iterdir()):
                if item.is_dir() and item.name not in ignored and (item / ".git").exists():
                    r_str = str(item.resolve())
                    if r_str not in seen:
                        seen.add(r_str)
                        repos.append({"name": item.name, "path": r_str, "branch": get_repo_branch(item)})
        except Exception:
            pass
    return repos


def auto_scan_servers_in_paths(paths: list[str]) -> dict:
    repos = scan_repositories_in_paths(paths)
    servers = {}
    used_ports = set()

    for r in repos:
        r_path = Path(r["path"])
        name = r["name"]
        srv_key = re.sub(r"[^a-zA-Z0-9_]", "_", name.lower()).strip("_") or "srv"

        # 1. Node / JS
        pkg_file = r_path / "package.json"
        if pkg_file.is_file():
            try:
                pkg_data = json.loads(pkg_file.read_text(encoding="utf-8"))
                deps = {**pkg_data.get("dependencies", {}), **pkg_data.get("devDependencies", {})}
                scripts = pkg_data.get("scripts", {})
                port = 3000
                while port in used_ports:
                    port += 1
                used_ports.add(port)

                cmd = "npm run dev" if "dev" in scripts else ("npm start" if "start" in scripts else "node index.js")
                tech = "Node.js"
                if "next" in deps:
                    tech = "Next.js"
                elif "vite" in deps:
                    tech = "Vite"
                    port = 5173 if 5173 not in used_ports else port
                elif "react-scripts" in deps:
                    tech = "React"

                servers[srv_key] = {
                    "title": f"{name} ({tech})",
                    "project": name,
                    "cwd": str(r_path),
                    "command": cmd,
                    "default_port": port,
                }
                continue
            except Exception:
                pass

        # 2. Django
        if (r_path / "manage.py").is_file():
            port = 8000
            while port in used_ports:
                port += 1
            used_ports.add(port)
            servers[srv_key] = {
                "title": f"{name} (Django)",
                "project": name,
                "cwd": str(r_path),
                "command": f"python3 manage.py runserver {port}",
                "default_port": port,
            }
            continue

        # 3. FastAPI / Flask / Python
        if (r_path / "main.py").is_file() or (r_path / "app.py").is_file():
            port = 8000
            while port in used_ports:
                port += 1
            used_ports.add(port)
            main_text = ""
            try:
                if (r_path / "main.py").is_file():
                    main_text = (r_path / "main.py").read_text(encoding="utf-8", errors="ignore")
                elif (r_path / "app.py").is_file():
                    main_text = (r_path / "app.py").read_text(encoding="utf-8", errors="ignore")
            except Exception:
                pass

            if "FastAPI" in main_text or "fastapi" in main_text:
                cmd = "uvicorn main:app --reload"
                tech = "FastAPI"
            elif "Flask" in main_text or "flask" in main_text:
                cmd = "flask run"
                tech = "Flask"
                port = 5000 if 5000 not in used_ports else port
            else:
                cmd = "python3 main.py" if (r_path / "main.py").is_file() else "python3 app.py"
                tech = "Python"

            servers[srv_key] = {
                "title": f"{name} ({tech})",
                "project": name,
                "cwd": str(r_path),
                "command": cmd,
                "default_port": port,
            }

    return servers


class SetupRequestHandler(http.server.BaseHTTPRequestHandler):
    def log_message(self, format, *args):
        pass

    def _is_safe_host(self) -> bool:
        host = self.headers.get("Host", "").split(":")[0].strip().lower()
        return host in ("localhost", "127.0.0.1", "::1", "")

    def _send_json(self, status_code: int, data: dict):
        body = json.dumps(data, ensure_ascii=False).encode("utf-8")
        self.send_response(status_code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("X-Frame-Options", "DENY")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        self.wfile.write(body)

    def do_OPTIONS(self):
        self.send_response(204)
        self.end_headers()

    def do_GET(self):
        if not self._is_safe_host():
            self.send_error(403, "Forbidden")
            return
        parsed = urllib.parse.urlparse(self.path)
        if parsed.path == "/":
            self.serve_html()
        elif parsed.path == "/api/config":
            env_data = parse_env_file(ENV_FILE)
            servers_data = read_json_safe(SERVERS_FILE, {})
            targets_data = read_json_safe(TARGETS_FILE, {})
            prompts_data = read_prompts()
            self._send_json(200, {
                "env": env_data,
                "servers": servers_data.get("servers", servers_data),
                "targets": targets_data.get("targets", targets_data),
                "prompts": prompts_data,
                "default_prompts": DEFAULT_PROMPTS,
            })
        elif parsed.path == "/api/select_folder":
            folder = select_folder_native()
            self._send_json(200, {"ok": True, "path": folder})
        else:
            self.send_error(404, "Not Found")

    def do_POST(self):
        if not self._is_safe_host():
            self.send_error(403, "Forbidden")
            return
        parsed = urllib.parse.urlparse(self.path)
        length = int(self.headers.get("Content-Length", 0))
        raw_body = self.rfile.read(length).decode("utf-8") if length > 0 else "{}"
        try:
            body = json.loads(raw_body)
        except Exception:
            body = {}

        if parsed.path in ("/api/test/telegram", "/api/validate/telegram"):
            token = body.get("token") or body.get("bot_token") or ""
            res = test_telegram_token(token.strip())
            self._send_json(200, res)

        elif parsed.path == "/api/detect/telegram_chat_id":
            token = body.get("token") or body.get("bot_token") or ""
            res = detect_telegram_chat_id(token.strip())
            self._send_json(200, res)

        elif parsed.path in ("/api/test/groq", "/api/validate/groq"):
            key = body.get("key") or body.get("api_key") or ""
            res = test_groq_key(key.strip())
            self._send_json(200, res)

        elif parsed.path in ("/api/test/github", "/api/validate/github"):
            token = body.get("token") or body.get("github_token") or ""
            res = test_github_token(token.strip())
            self._send_json(200, res)

        elif parsed.path == "/api/scan/repos":
            paths = body.get("paths") or body.get("base_dirs") or []
            if isinstance(paths, str):
                paths = [p.strip() for p in paths.split(",") if p.strip()]
            repos = scan_repositories_in_paths(paths)
            self._send_json(200, {"ok": True, "repos": repos, "count": len(repos)})

        elif parsed.path == "/api/scan/servers":
            paths = body.get("paths") or body.get("base_dirs") or []
            if isinstance(paths, str):
                paths = [p.strip() for p in paths.split(",") if p.strip()]
            servers = auto_scan_servers_in_paths(paths)
            self._send_json(200, {"ok": True, "servers": servers, "count": len(servers)})

        elif parsed.path == "/api/save":
            try:
                env_in = body.get("env", {})
                servers_in = body.get("servers", {})
                targets_in = body.get("targets", {})
                prompts_in = body.get("prompts", {})

                write_env_file(ENV_FILE, env_in)

                with open(SERVERS_FILE, "w", encoding="utf-8") as f:
                    json.dump({"servers": servers_in}, f, ensure_ascii=False, indent=2)

                with open(TARGETS_FILE, "w", encoding="utf-8") as f:
                    json.dump({"targets": targets_in}, f, ensure_ascii=False, indent=2)

                if prompts_in and isinstance(prompts_in, dict):
                    write_prompts(prompts_in)

                self._send_json(200, {
                    "ok": True,
                    "message": "تم حفظ الإعدادات بنجاح في .env و servers.json و targets.json ومجلد prompts. يمكنك الآن تشغيل البوت عبر: ./scripts/run_bot.sh"
                })
            except Exception as exc:
                self._send_json(500, {"ok": False, "error": str(exc)})
        else:
            self.send_error(404, "Not Found")

