def safe_urlopen(req: urllib.request.Request, timeout: int = 10):
    try:
        return urllib.request.urlopen(req, timeout=timeout)
    except urllib.error.URLError as e:
        if "CERTIFICATE_VERIFY_FAILED" in str(e):
            ctx = ssl._create_unverified_context()
            return urllib.request.urlopen(req, timeout=timeout, context=ctx)
        raise


def test_telegram_token(token: str) -> dict:
    if not token:
        return {"ok": False, "error": "يرجى إدخال توكن البوت أولاً."}
    url = f"https://api.telegram.org/bot{token}/getMe"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "SetupWizard/1.0"})
        with safe_urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            if data.get("ok"):
                user = data.get("result", {})
                return {
                    "ok": True,
                    "name": user.get("first_name", ""),
                    "username": user.get("username", ""),
                    "id": user.get("id"),
                }
            return {"ok": False, "error": data.get("description", "Unknown error")}
    except urllib.error.HTTPError as exc:
        try:
            d = json.loads(exc.read().decode("utf-8", errors="ignore"))
            return {"ok": False, "error": d.get("description", f"HTTP {exc.code}")}
        except Exception:
            return {"ok": False, "error": f"HTTP {exc.code}: {exc.reason}"}
    except Exception as exc:
        return {"ok": False, "error": str(exc)}


def detect_telegram_chat_id(token: str) -> dict:
    if not token:
        return {"ok": False, "error": "يرجى إدخال توكن البوت أولاً لتتمكن من فحص الرسائل."}
    url = f"https://api.telegram.org/bot{token}/getUpdates?limit=20&offset=-10"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "SetupWizard/1.0"})
        with safe_urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            if not data.get("ok"):
                return {"ok": False, "error": data.get("description", "Unknown error")}
            updates = data.get("result", [])
            if not updates:
                return {
                    "ok": False,
                    "error": "لم يتم رصد أي رسائل واردة للبوت بعد. يرجى فتح البوت في تطبيق تيليجرام وإرسال أي رسالة له (مثل /start)، ثم الضغط على هذا الزر مجدداً.",
                }
            for item in reversed(updates):
                msg = item.get("message") or item.get("edited_message") or item.get("channel_post") or item.get("callback_query", {}).get("message")
                from_u = (item.get("message") or item.get("callback_query", {})).get("from", {})
                chat = msg.get("chat", {}) if msg else {}
                chat_id = from_u.get("id") or chat.get("id")
                if chat_id:
                    return {
                        "ok": True,
                        "chat_id": str(chat_id),
                        "name": from_u.get("first_name", "") or chat.get("title", ""),
                        "username": from_u.get("username", "") or chat.get("username", ""),
                    }
            return {
                "ok": False,
                "error": "تعذر استخراج معرّف مستخدم صالح من الرسائل الأخيرة. أرسل رسالة نصية جديدة للبوت ثم أعد المحاولة.",
            }
    except urllib.error.HTTPError as exc:
        try:
            d = json.loads(exc.read().decode("utf-8", errors="ignore"))
            return {"ok": False, "error": d.get("description", f"HTTP {exc.code}")}
        except Exception:
            return {"ok": False, "error": f"HTTP {exc.code}: {exc.reason}"}
    except Exception as exc:
        return {"ok": False, "error": str(exc)}


def test_groq_key(key: str) -> dict:
    if not key:
        return {"ok": False, "error": "يرجى إدخال مفتاح Groq أولاً."}
    url = "https://api.groq.com/openai/v1/models"
    try:
        req = urllib.request.Request(
            url,
            headers={
                "Authorization": f"Bearer {key}",
                "User-Agent": "SetupWizard/1.0",
            },
        )
        with safe_urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            models = [m.get("id") for m in data.get("data", []) if m.get("id")]
            return {"ok": True, "models_count": len(models), "models": models[:6]}
    except urllib.error.HTTPError as exc:
        try:
            d = json.loads(exc.read().decode("utf-8", errors="ignore"))
            msg = d.get("error", {}).get("message") or d.get("description")
            return {"ok": False, "error": msg or f"HTTP {exc.code}"}
        except Exception:
            return {"ok": False, "error": f"HTTP {exc.code}: {exc.reason}"}
    except Exception as exc:
        return {"ok": False, "error": str(exc)}


